"""Generate the Möbius UI modules from frontend/index.html (run by sync.sh).

frontend/index.html stays the one UI source. This script splits it into
  ui_css.js     style, with the design tokens mapped onto the owner's Möbius theme
  ui_markup.js  body markup (header, layout, sidebar, toasts)
  ui_desk.js    the script wrapped as start(env); env supplies the Möbius transport,
                storage-backed localStorage, push-backed Notification and theme colours.
Each replacement must match exactly once, so a changed frontend fails here loudly instead
of shipping a half-ported UI. Edit frontend/index.html (or the rules below), never the output.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "frontend" / "index.html"

# Design tokens follow the Möbius theme (light or dark): --bg, --surface, --surface-2, --border,
# --text, --muted, --accent and --font come from Möbius; the rest are derived from them.
ROOT_TOKENS = """:root{
  --surface-3:color-mix(in srgb,var(--surface-2) 88%,var(--text));
  --faint:color-mix(in srgb,var(--muted) 72%,var(--bg));
  --brand:var(--accent); --brand-2:color-mix(in srgb,var(--accent) 60%,#ec4899);
  --brand-grad:linear-gradient(135deg,var(--brand) 0%,var(--brand-2) 100%);
  --up:#22c55e; --down:#ef4444; --warn:#f59e0b; --info:#38bdf8;
  --r-sm:8px; --r:12px; --r-lg:18px;
  --s1:4px; --s2:8px; --s3:12px; --s4:16px; --s5:24px; --s6:32px; --s7:48px;
  --shadow:0 10px 30px rgba(0,0,0,.35);
}"""

CSS_RULES = [
    (r'@font-face\{[^}]*\}\n', ""),                       # Inter comes from the Möbius font stack
    (r':root\{[^}]*\}', ROOT_TOKENS),
    (r'header\{position:sticky;top:0;z-index:20;background:rgba\(7,11,20,\.85\)',
     'header{position:sticky;top:0;z-index:20;background:color-mix(in srgb,var(--bg) 86%,transparent)'),
    (r'\.chipT:hover\{border-color:var\(--brand\);color:#fff\}', '.chipT:hover{border-color:var(--brand);color:var(--text)}'),
    (r'background:rgba\(14,21,35,\.75\)', 'background:color-mix(in srgb,var(--surface) 78%,transparent)'),
]
# Brand glows were written as the old brand colours' rgba(); keep them tied to the theme accent.
CSS_RGBA = [("91,124,255", "var(--brand)"), ("139,92,246", "var(--brand-2)")]

JS_RULES = [
    # All requests go through the Möbius app service (and the AI flow for /brief and /chat).
    (r'const J=\(u,o\)=>fetch\(u,o\)\.then\(', 'const J=(u,o)=>api(u,o).then('),
    # Chart colours follow the theme; lightweight-charts needs concrete colours, read at draw time.
    (r'textColor:"#8b97ab",fontFamily:"Inter, system-ui, sans-serif"', 'textColor:cssVar("--muted"),fontFamily:cssVar("--font")'),
    (r'horzLines:\{color:"#1a2438"\}', 'horzLines:{color:cssVar("--border")}'),
    (r'vertLine:\{labelBackgroundColor:"#5b7cff"\},horzLine:\{labelBackgroundColor:"#5b7cff"\}',
     'vertLine:{labelBackgroundColor:cssVar("--accent")},horzLine:{labelBackgroundColor:cssVar("--accent")}'),
    (r'setInterval\(tick,LIVE_MS\);document\.addEventListener\("visibilitychange",\(\)=>\{if\(!document\.hidden\)tick\(\)\}\);',
     'every(tick,LIVE_MS);onVisible(()=>{if(!document.hidden)tick()});'),
    # Möbius ranks people (@handle) in the competition card instead of workspaces; the service
    # reports workspace_leaderboard: false, so the workspace card stays hidden and never polls.
    (r'async function lbUI\(\)\{if\(!feat\.paper\)return;',
     'async function lbUI(){if(!feat.paper||feat.workspace_leaderboard===false)return;'),
    # Alerts are checked while the app is open; they now arrive as Möbius notifications.
    (r'We\'ll notify you when \$\{t\} crosses the price you enter \(while Finance Desk is open\)\.',
     "We'll send you a Möbius notification when ${t} crosses the price you enter (checked while Finance Desk is open)."),
]


def sub_once(text: str, pattern: str, repl: str, what: str) -> str:
    out, n = re.subn(pattern, lambda _: repl, text)
    if n != 1:
        sys.exit(f"port_ui: expected exactly one match for {what!r} ({pattern}), found {n}")
    return out


def main() -> None:
    html = SRC.read_text(encoding="utf-8")
    css = re.search(r"<style>\n?(.*?)</style>", html, re.S).group(1)
    body = re.search(r"<body>\n?(.*?)<script>", html, re.S).group(1)
    script = re.search(r"<script>\n?(.*?)</script>\s*</body>", html, re.S).group(1)

    for pattern, repl in CSS_RULES:
        css = sub_once(css, pattern, repl, "css")
    for rgb, var in CSS_RGBA:
        css = re.sub(rf"rgba\({rgb},(\.?\d+)\)",
                     lambda m: f"color-mix(in srgb,{var} {round(float(m.group(1)) * 100)}%,transparent)", css)
    for pattern, repl in JS_RULES:
        script = sub_once(script, pattern, repl, "js")

    banner = "// GENERATED by mobius/port_ui.py from frontend/index.html. Edit the source, not this file.\n"
    (HERE / "ui_css.js").write_text(banner + "export const CSS = " + json.dumps(css, ensure_ascii=False) + "\n", encoding="utf-8")
    (HERE / "ui_markup.js").write_text(banner + "export const MARKUP = " + json.dumps(body, ensure_ascii=False) + "\n", encoding="utf-8")
    (HERE / "ui_desk.js").write_text(
        banner
        + "// env: api, localStorage, Notification, cssVar, every, onVisible (see runtime.js).\n"
        + "export function start({ api, localStorage, Notification, cssVar, every, onVisible }) {\n"
        + script
        + "}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
